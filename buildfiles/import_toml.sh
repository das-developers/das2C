#!/usr/bin/env bash
#
# Bring CK Tan's tomlc17 parser into das2C as das3/toml.h and das3/toml.c
#
# usage: buildfiles/import_toml.sh UPSTREAM_SRC_DIR [UPSTREAM_COMMIT]
#
# UPSTREAM_SRC_DIR holds pristine tomlc17.h and tomlc17.c, the src/ directory
# of https://github.com/cktan/tomlc17.  Run from the top of the das2C tree.
# Never hand edit das3/toml.[ch]; change this script and re-run it so the next
# upstream update gets the same treatment.
#
# What it does, and why:
#
#   toml_*  -> dastoml_*    Every public name gets a das prefix, the same as
#   TOML_*  -> DASTOML_*    json.h did.  Without it a reader that also links
#   TOMLC17_ -> DASTOMLC17_ tomlc99 or its own tomlc17 collides with libdas3,
#                           and against the shared library its toml_parse()
#                           call can bind to ours (different signature).
#
#   DASTOML_EXTERN DAS_API  Upstream marks exactly its entry points with
#                           TOML_EXTERN, so DAS_API goes on all of them for
#                           the Windows DLL and GCC visibility builds.
#
#   static DATUM_ZERO       The one file scope variable that wasn't static,
#                           nothing outside toml.c uses it.
#
# The script refuses to write anything if a rule stops matching, that means
# upstream changed shape and the rules need a look.

set -euo pipefail

if [ $# -lt 1 ] || [ ! -f "$1/tomlc17.h" ] || [ ! -f "$1/tomlc17.c" ]; then
	echo "usage: $0 UPSTREAM_SRC_DIR [UPSTREAM_COMMIT]" >&2
	exit 3
fi
SRC=$1
COMMIT=${2:-unknown}

if [ ! -f das3/defs.h ]; then
	echo "$0: run from the top of the das2C tree" >&2
	exit 3
fi

TMP=$(mktemp -d)
trap 'rm -rf -- "${TMP:?}"' EXIT

# Identifier renames, \b keeps already prefixed names from matching again
_rename(){
	sed -E \
		-e 's/\btoml_/dastoml_/g' \
		-e 's/\bTOML_/DASTOML_/g' \
		-e 's/\bTOMLC17_/DASTOMLC17_/g' \
		-e 's/\bDATUM_ZERO\b/DASTOML_DATUM_ZERO/g' \
		"$1"
}

_require(){  # file pattern what
	if ! grep -qE "$2" "$1"; then
		echo "$0: upstream changed, no match for $3 in $(basename "$1")" >&2
		exit 4
	fi
}

NOTE="/* das2C: generated by buildfiles/import_toml.sh, do not edit.  From
 * tomlc17 commit $COMMIT
 * Public names carry the dastoml_ and DASTOML_ prefixes and the entry points
 * carry DAS_API, see the script for why. */"

# Header ######################################################################

_require "$SRC/tomlc17.h" '^TOML_EXTERN ' 'TOML_EXTERN entry points'
_require "$SRC/tomlc17.h" '^#include <stdio.h>' 'the stdio.h include'
_require "$SRC/tomlc17.h" '@file tomlc17\.h' 'the @file line'

_rename "$SRC/tomlc17.h" | awk -v note="$NOTE" '
	# note after the license comment, which ends on the first "*/" line
	!bNote && /\*\// { print; print ""; print note; bNote = 1; next }
	/^#include <stdio.h>/ && !bInc {
		print; print ""; print "#include <das3/defs.h>  /* das2C: DAS_API */"
		bInc = 1; next
	}
	{ sub(/@file tomlc17\.h/, "@file toml.h") }
	/^DASTOML_EXTERN / { sub(/^DASTOML_EXTERN /, "DASTOML_EXTERN DAS_API ") }
	{ print }
' > "$TMP/toml.h"

# Source ######################################################################

_require "$SRC/tomlc17.c" '^#include "tomlc17\.h"' 'the tomlc17.h include'
_require "$SRC/tomlc17.c" '^const toml_datum_t DATUM_ZERO' 'DATUM_ZERO'

_rename "$SRC/tomlc17.c" | awk -v note="$NOTE" '
	!bNote && /\*\// { print; print ""; print note; bNote = 1; next }
	/^#include "tomlc17\.h"/ { print "#include \"toml.h\""; next }
	/^const dastoml_datum_t DASTOML_DATUM_ZERO/ { print "static " $0; next }
	{ print }
' > "$TMP/toml.c"

# Checks ######################################################################

# Nothing unprefixed may survive outside comments and the license URL
for f in toml.h toml.c; do
	if sed -E 's@//.*$@@; s@https?://[^ ]*@@g' "$TMP/$f" \
		| grep -nE '\b(toml_|TOML_|TOMLC17_)'; then
		echo "$0: unprefixed names left in $f" >&2
		exit 4
	fi
done

nExtern=$(grep -cE '^DASTOML_EXTERN ' "$TMP/toml.h")
nApi=$(grep -cE '^DASTOML_EXTERN DAS_API ' "$TMP/toml.h")
if [ "$nExtern" -ne "$nApi" ] || [ "$nApi" -lt 1 ]; then
	echo "$0: $nApi of $nExtern entry points tagged DAS_API" >&2
	exit 4
fi

cp "$TMP/toml.h" das3/toml.h
cp "$TMP/toml.c" das3/toml.c
echo "Wrote das3/toml.h and das3/toml.c, $nApi entry points, from $COMMIT"
